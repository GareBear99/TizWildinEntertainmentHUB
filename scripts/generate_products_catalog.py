#!/usr/bin/env python3
"""Regenerate manifests/products.catalog.json from plugins.json.

plugins.json is the single source of truth for the plugin catalog (it is
what the live site reads). manifests/products.catalog.json is a derived view
of it in the manifest schema used by scripts/generate_release_manifest.py
and the ARC store mock data — do not edit it by hand.

Usage: python3 scripts/generate_products_catalog.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLUGINS_PATH = ROOT / "plugins.json"
CATALOG_PATH = ROOT / "manifests" / "products.catalog.json"


def main() -> None:
    plugins = json.loads(PLUGINS_PATH.read_text(encoding="utf-8"))

    groups = []
    for cat in plugins["categories"]:
        members = [p["id"] for p in plugins["plugins"] if p["category"] == cat["id"]]
        groups.append({
            "groupId": cat["id"],
            "displayName": cat["name"],
            "products": members,
        })

    products = []
    for p in plugins["plugins"]:
        products.append({
            "productId": p["id"],
            "displayName": p["name"],
            "groupId": p["category"],
            "edition": "free",
            "licenseClass": "FREE_OPEN",
            "status": "source_ready",
            "includedInOwnsEveryVST": False,
            "priceModel": "free",
            "freeVersionAvailable": True,
            "paymentSurface": "in_product",
            "distributionMode": "release_or_source",
            "repo": p["repo"],
            "formats": list(p["formats"]),
            "developmentStage": p["status"],
        })

    catalog = {
        "_generatedFrom": "plugins.json — generated by scripts/generate_products_catalog.py; do not edit by hand.",
        "groups": groups,
        "products": products,
        "globalFlags": {
            "hubActsAs": "updater_version_controller_downloader",
            "defaultDelivery": "free_versions_first",
            "pluginPayments": "inside_each_product",
        },
    }

    CATALOG_PATH.write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {CATALOG_PATH} ({len(products)} products)")


if __name__ == "__main__":
    main()
